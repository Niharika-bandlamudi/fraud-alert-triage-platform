#!/usr/bin/env python3
"""Export the final dataset as SQL seed data and JSON (standard library only).

  exports/seed.sql          CREATE TABLE (primary and foreign keys) plus INSERT statements.
                            Standard SQL types, loads as-is into SQLite and, with minor type changes, other databases.
  exports/json/<table>.json one JSON array of records per table (empty optional fields become null)
  exports/load_check.txt    result of loading seed.sql into an in-memory SQLite database

Run:  python src/export_seed.py --data data_final --out exports
Deterministic: the same CSV files always give byte-identical output.
"""
import argparse, csv, json, os, sqlite3

# table -> (columns with type, primary key, [(column, parent table, parent column)])
SCHEMA = {
    "customers": ("customer_id", [], dict(date_of_birth="DATE", onboarded_at="TIMESTAMP", kyc_verified_at="TIMESTAMP")),
    "accounts": ("account_id", [("customer_id", "customers", "customer_id")],
                 dict(opened_at="TIMESTAMP", closed_at="TIMESTAMP", overdraft_limit="DECIMAL(14,2)", opening_balance="DECIMAL(14,2)",
                      current_balance="DECIMAL(14,2)")),
    "account_status_history": ("history_id", [("account_id", "accounts", "account_id")], dict(changed_at="TIMESTAMP")),
    "merchants": ("merchant_id", [], {}),
    "devices": ("device_id", [], dict(first_seen_at="TIMESTAMP")),
    "device_account_links": ("link_id", [("device_id", "devices", "device_id"), ("account_id", "accounts", "account_id")],
                             dict(first_seen_at="TIMESTAMP", last_seen_at="TIMESTAMP")),
    "transactions": ("transaction_id", [("account_id", "accounts", "account_id"), ("merchant_id", "merchants", "merchant_id"),
                                        ("device_id", "devices", "device_id")],
                     dict(txn_timestamp="TIMESTAMP", amount="DECIMAL(14,2)", balance_after="DECIMAL(14,2)")),
    "transfer_links": ("transfer_id", [("debit_txn_id", "transactions", "transaction_id"), ("credit_txn_id", "transactions", "transaction_id"),
                                       ("source_account_id", "accounts", "account_id"), ("destination_account_id", "accounts", "account_id")],
                       dict(transfer_amount="DECIMAL(14,2)", initiated_at="TIMESTAMP")),
    "risk_rules": ("rule_id", [], dict(weight="INTEGER", effective_from="DATE", effective_to="DATE", is_active="BOOLEAN")),
    "alerts": ("alert_id", [("rule_id", "risk_rules", "rule_id"), ("transaction_id", "transactions", "transaction_id"),
                            ("account_id", "accounts", "account_id")], dict(created_at="TIMESTAMP", risk_score="INTEGER")),
    "cases": ("case_id", [("customer_id", "customers", "customer_id")], dict(opened_at="TIMESTAMP", priority_score="INTEGER", closed_at="TIMESTAMP")),
    "case_alerts": ("case_alert_id", [("case_id", "cases", "case_id"), ("alert_id", "alerts", "alert_id")], dict(linked_at="TIMESTAMP")),
    "analyst_actions": ("action_id", [("case_id", "cases", "case_id"), ("alert_id", "alerts", "alert_id")], dict(action_timestamp="TIMESTAMP")),
    "ground_truth": ("truth_id", [], {}),
}
UNIQUE = {"case_alerts": ["alert_id"], "device_account_links": ["device_id, account_id"]}
BATCH = 500


def read(folder, name):
    with open(os.path.join(folder, name + ".csv"), newline="", encoding="utf-8") as f:
        r = csv.reader(f)
        head = next(r)
        return head, list(r)


def lit(v, typ):
    if v == "":
        return "NULL"
    if typ in ("INTEGER", "BOOLEAN") or typ.startswith("DECIMAL"):
        if typ == "BOOLEAN":
            return "1" if v == "true" else "0"
        return v
    return "'" + v.replace("'", "''") + "'"


def sql_for(folder):
    out = ["-- Fraud alert triage platform: SQL seed data (synthetic). Generated by src/export_seed.py", "PRAGMA foreign_keys = ON;", ""]
    counts = {}
    for name, (pk, fks, types) in SCHEMA.items():
        head, rows = read(folder, name)
        counts[name] = len(rows)
        cols = []
        for c in head:
            t = types.get(c, "TEXT")
            nn = " NOT NULL" if c == pk else ""
            cols.append(f"  {c} {t}{nn}")
        cons = [f"  PRIMARY KEY ({pk})"]
        cons += [f"  FOREIGN KEY ({c}) REFERENCES {p}({pc})" for c, p, pc in fks]
        cons += [f"  UNIQUE ({u})" for u in UNIQUE.get(name, [])]
        out.append(f"CREATE TABLE {name} (\n" + ",\n".join(cols + cons) + "\n);")
        tmap = [types.get(c, "TEXT") for c in head]
        for i in range(0, len(rows), BATCH):
            vals = ",\n".join("  (" + ", ".join(lit(v, t) for v, t in zip(r, tmap)) + ")" for r in rows[i:i + BATCH])
            out.append(f"INSERT INTO {name} ({', '.join(head)}) VALUES\n{vals};")
        out.append("")
    return "\n".join(out), counts


def json_for(folder, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    for name, (_pk, _fks, types) in SCHEMA.items():
        head, rows = read(folder, name)
        recs = []
        for r in rows:
            d = {}
            for c, v in zip(head, r):
                t = types.get(c, "TEXT")
                if v == "":
                    d[c] = None
                elif t == "INTEGER":
                    d[c] = int(v)
                elif t == "BOOLEAN":
                    d[c] = v == "true"
                elif t.startswith("DECIMAL"):
                    d[c] = float(v)
                else:
                    d[c] = v
            recs.append(d)
        with open(os.path.join(out_dir, name + ".json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(recs, f, separators=(",", ":"), ensure_ascii=False)
            f.write("\n")


def load_check(sql, counts):
    con = sqlite3.connect(":memory:")
    con.executescript(sql)
    bad = con.execute("PRAGMA foreign_key_check").fetchall()
    lines = ["Loaded seed.sql into in-memory SQLite with foreign keys on."]
    ok = not bad
    for n, c in counts.items():
        got = con.execute(f"SELECT COUNT(*) FROM {n}").fetchone()[0]
        ok &= got == c
        lines.append(f"  {n:24s} {got:>8,} rows {'OK' if got == c else 'MISMATCH (expected ' + str(c) + ')'}")
    lines.append(f"foreign_key_check violations: {len(bad)}")
    lines.append("RESULT: " + ("PASS" if ok else "FAIL"))
    return "\n".join(lines), ok


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default="data_final")
    ap.add_argument("--out", default="exports")
    ap.add_argument("--no-json", action="store_true", help="skip the per-table JSON files")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    sql, counts = sql_for(a.data)
    with open(os.path.join(a.out, "seed.sql"), "w", encoding="utf-8", newline="\n") as f:
        f.write(sql)
    if not a.no_json:
        json_for(a.data, os.path.join(a.out, "json"))
    report, ok = load_check(sql, counts)
    with open(os.path.join(a.out, "load_check.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(report + "\n")
    print(report)
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()
